// ===============================
// UPDATE ADVANCE
// ===============================
exports.updateAdvance = async (req, res) => {
  try {
    const { id } = req.params;
    const { amount, date, notes, month } = req.body;

    const advance = await Advance.findById(id);
    if (!advance) {
      return res.status(404).json({
        success: false,
        message: "Advance not found"
      });
    }

    const oldAmount = advance.amount;
    const oldMonth = advance.month;

    // Check if salary already exists for the new month
    if (month && month !== oldMonth) {
      const Salary = require("../models/Salary.model");
      const existingSalary = await Salary.findOne({ 
        staffId: advance.staffId, 
        month: month 
      });
      
      if (existingSalary) {
        return res.status(400).json({
          success: false,
          message: `Cannot change month to ${month} because salary has already been processed for this month.`
        });
      }
    }

    // Update fields
    if (amount !== undefined) advance.amount = Number(amount);
    if (date) advance.date = date;
    if (notes !== undefined) advance.notes = notes;
    if (month) advance.month = month;

    await advance.save();

    console.log(`✅ Advance updated: ${advance.paymentNo} - Amount: ${oldAmount} -> ${advance.amount}, Month: ${oldMonth} -> ${advance.month}`);

    // If amount changed, update account ledger
    if (amount !== undefined && oldAmount !== amount) {
      try {
        const Account = require("../models/Account.model");
        await Account.findOneAndUpdate(
          { sourceModule: "advance", sourceId: advance._id },
          { 
            expense: Number(amount),
            notes: notes || `Salary advance updated - ${advance.paymentNo}`
          }
        );
        console.log(`✅ Advance account transaction updated: ${advance.paymentNo}`);
      } catch (accountErr) {
        console.error("Failed to update account ledger:", accountErr);
      }
    }

    const populatedAdvance = await Advance.findById(advance._id)
      .populate("staffId", "fullName username role basicSalary");

    res.json({
      success: true,
      message: "Advance updated successfully",
      advance: populatedAdvance
    });
  } catch (error) {
    console.error("Error in updateAdvance:", error);
    res.status(500).json({
      success: false,
      message: error.message
    });
  }
};

// ===============================
// DELETE ADVANCE (with account reversal)
// ===============================
exports.deleteAdvance = async (req, res) => {
  try {
    const { id } = req.params;

    const advance = await Advance.findById(id);
    if (!advance) {
      return res.status(404).json({
        success: false,
        message: "Advance not found"
      });
    }

    // Check if salary already exists for this month
    const Salary = require("../models/Salary.model");
    const existingSalary = await Salary.findOne({ 
      staffId: advance.staffId, 
      month: advance.month 
    });
    
    if (existingSalary) {
      return res.status(400).json({
        success: false,
        message: `Cannot delete advance for ${advance.month} because salary has already been processed for this month. Please adjust the salary instead.`
      });
    }

    console.log(`Deleting advance: ${advance.paymentNo} for amount ${advance.amount}`);

    // =====================
    // DELETE FROM ACCOUNT LEDGER
    // =====================
    try {
      const Account = require("../models/Account.model");
      const deleted = await Account.deleteOne({ 
        sourceModule: "advance", 
        sourceId: advance._id 
      });
      if (deleted.deletedCount > 0) {
        console.log(`✅ Advance account transaction deleted: ${advance.paymentNo}`);
      }
    } catch (accountErr) {
      console.error("Failed to delete from account ledger:", accountErr);
    }

    await Advance.findByIdAndDelete(id);

    res.json({
      success: true,
      message: "Advance deleted successfully"
    });
  } catch (error) {
    console.error("Error in deleteAdvance:", error);
    res.status(500).json({
      success: false,
      message: error.message
    });
  }
};

// ===============================
// GET TOTAL ADVANCES FOR STAFF (ALL TIME)
// ===============================
exports.getStaffAdvanceTotal = async (req, res) => {
  try {
    const { staffId } = req.params;

    const advances = await Advance.find({ staffId });
    const totalAmount = advances.reduce((sum, adv) => sum + adv.amount, 0);
    const advanceCount = advances.length;

    // Group by month
    const byMonth = {};
    advances.forEach(adv => {
      if (adv.month) {
        byMonth[adv.month] = (byMonth[adv.month] || 0) + adv.amount;
      }
    });

    res.json({
      success: true,
      staffId,
      totalAmount,
      advanceCount,
      byMonth,
      advances
    });
  } catch (error) {
    console.error("Error in getStaffAdvanceTotal:", error);
    res.status(500).json({
      success: false,
      message: error.message
    });
  }
};