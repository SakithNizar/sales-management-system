const Advance = require("../models/Advance.model");
const User = require("../models/User.model");
const { addTransaction } = require("../services/accountService");

// ===============================
// ADD ADVANCE (ADMIN ONLY)
// ===============================
exports.createAdvance = async (req, res) => {
  try {
    const { staffId, amount, date, notes, month } = req.body;

    console.log("Creating advance with:", { staffId, amount, date, notes, month });

    // Validate required fields
    if (!staffId) {
      return res.status(400).json({
        success: false,
        message: "Staff ID is required"
      });
    }

    if (!amount || amount <= 0) {
      return res.status(400).json({
        success: false,
        message: "Valid advance amount is required"
      });
    }

    if (!month) {
      return res.status(400).json({
        success: false,
        message: "Month is required (e.g., 'June 2026') - this determines when advance will be deducted"
      });
    }

    // Check staff exists
    const staff = await User.findById(staffId);
    if (!staff) {
      return res.status(404).json({
        success: false,
        message: "Staff not found"
      });
    }

    // Check if advance amount exceeds basic salary
    if (amount > (staff.basicSalary || 0)) {
      return res.status(400).json({
        success: false,
        message: `Advance amount (${amount}) cannot exceed basic salary (${staff.basicSalary || 0})`
      });
    }

    // Check if there's already a salary for this month (can't add advance after salary is processed)
    const Salary = require("../models/Salary.model");
    const existingSalary = await Salary.findOne({ 
      staffId: staffId, 
      month: month 
    });
    
    if (existingSalary) {
      return res.status(400).json({
        success: false,
        message: `Cannot add advance for ${month} because salary has already been processed for this month. Please adjust the salary instead.`
      });
    }

    // Create advance record - paymentNo will be auto-generated by the model
    const advance = await Advance.create({
      staffId,
      amount: Number(amount),
      date: date || new Date(),
      month: month,
      notes: notes || "",
      createdBy: req.user._id
      // paymentNo is auto-generated by the model's default function
    });

    console.log(`✅ Advance created for ${staff.fullName} - Amount: ${amount} for month: ${month}, Payment No: ${advance.paymentNo}`);

    // =====================
    // ADD TO ACCOUNT LEDGER
    // =====================
    try {
      await addTransaction({
        date: date || new Date(),
        invoiceNo: advance.paymentNo, // Use the auto-generated paymentNo
        description: `Salary Advance - ${staff.fullName} (Deduct from ${month})`,
        income: 0,
        expense: Number(amount),
        sourceModule: "advance",
        sourceId: advance._id,
        enteredBy: req.user._id,
        notes: notes || `Salary advance payment for ${staff.fullName} - will be deducted from ${month} salary`
      });
      console.log(`✅ Advance transaction added to accounts for ${staff.fullName} - LKR ${amount}`);
    } catch (accountErr) {
      console.error("Failed to add advance to account ledger:", accountErr);
      // Don't fail the advance creation if account recording fails
    }

    // Populate staff details for response
    const populatedAdvance = await Advance.findById(advance._id)
      .populate("staffId", "fullName username role basicSalary");

    res.status(201).json({
      success: true,
      message: "Advance added successfully",
      advance: populatedAdvance
    });
  } catch (error) {
    console.error("Error in createAdvance:", error);
    res.status(500).json({
      success: false,
      message: error.message
    });
  }
};

